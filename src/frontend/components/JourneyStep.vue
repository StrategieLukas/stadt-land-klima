<template>
  <div :id="`step-${step.index}`" class="scroll-mt-32 border-b border-gray-100 py-8 last:border-b-0">
    <!-- Step header -->
    <div class="mb-6">
      <div class="mb-2 flex items-center gap-2">
        <span
          class="flex h-6 w-6 flex-none items-center justify-center rounded-full bg-[#006e94]/10 text-xs font-bold text-[#006e94]"
        >
          {{ step.index + 1 }}
        </span>
        <h3 class="text-base leading-snug font-semibold text-gray-900">{{ t(step.title) }}</h3>
      </div>
      <p v-if="t(step.description)" class="pl-8 text-sm leading-relaxed text-gray-600">
        {{ t(step.description) }}
      </p>
    </div>

    <!-- Layout: kpi_map — KPI left (40%) + map right (60%) -->
    <div
      v-if="step.layout === 'kpi_map' && mapElement && kpiElement"
      class="grid grid-cols-1 items-start gap-4 sm:grid-cols-5"
    >
      <div class="sm:col-span-2">
        <KPICard
          :element="kpiElement"
          :collection-slug="collection.id"
          :ars="ars"
          :base-url="baseUrl"
          :summary="summary"
          :population="population"
        />
      </div>
      <div class="sm:col-span-3" style="height: 340px">
        <ClientOnly v-if="mapLibreSpec(mapElement)"
          ><MapLibreRenderElement
            :element="mapElement"
            :ars="ars"
            :export-area-name="areaName"
            :export-ars="ars"
            :export-title="localizedElementTitle(mapElement) || stepTitle"
            :export-subtitle="localizedElementDescription(mapElement) || stepDescription"
            :export-collection-name="collectionTitle"
            :export-updated-at="exportUpdatedAt"
            :export-attribution="exportAttribution"
        /></ClientOnly>
        <CollectionVegaChart
          v-else-if="mapSpec"
          :ars="ars"
          :element="mapElement"
          :collection-id="collection.id"
          :spec="mapSpec"
          :height="340"
          :export-area-name="areaName"
          :export-ars="ars"
          :export-title="localizedElementTitle(mapElement) || stepTitle"
          :export-subtitle="localizedElementDescription(mapElement) || stepDescription"
          :export-collection-name="collectionTitle"
          :export-updated-at="exportUpdatedAt"
          :export-attribution="exportAttribution"
        />
      </div>
    </div>
    <!-- kpi_map with no map: fall back to KPICard alone -->
    <div v-else-if="step.layout === 'kpi_map' && kpiElement">
      <KPICard
        :element="kpiElement"
        :collection-slug="collection.id"
        :ars="ars"
        :base-url="baseUrl"
        :summary="summary"
        :population="population"
      />
    </div>
    <!-- kpi_map with no KPI element: full DataProductPanel fallback -->
    <div v-else-if="step.layout === 'kpi_map'">
      <DataProductPanel
        v-if="kpiCollection"
        :collection="kpiCollection"
        :ars="ars"
        :base-url="baseUrl"
        :initial-summary="summary"
        :population="population ?? undefined"
        :municipality-name="areaName"
        :export-updated-at="exportUpdatedAt"
        :export-attribution="exportAttribution"
      />
    </div>

    <!-- Layout: full_width — single chart spanning full width -->
    <div
      v-else-if="step.layout === 'full_width' && (primaryMapLibreSpec || primarySpec)"
      class="w-full"
      :style="primaryElement?.type === 'histogram' ? undefined : { height: '360px' }"
    >
      <ClientOnly v-if="primaryMapLibreSpec && primaryElement"
        ><MapLibreRenderElement
          :element="primaryElement"
          :ars="ars"
          :export-area-name="areaName"
          :export-ars="ars"
          :export-title="localizedElementTitle(primaryElement) || stepTitle"
          :export-subtitle="localizedElementDescription(primaryElement) || stepDescription"
          :export-collection-name="collectionTitle"
          :export-updated-at="exportUpdatedAt"
          :export-attribution="exportAttribution"
      /></ClientOnly>
      <CollectionVegaChart
        v-else-if="primarySpec"
        :ars="ars"
        :element="primaryElement"
        :collection-id="collection.id"
        :spec="primarySpec"
        :height="360"
        :export-area-name="areaName"
        :export-ars="ars"
        :export-title="localizedElementTitle(primaryElement) || stepTitle"
        :export-subtitle="localizedElementDescription(primaryElement) || stepDescription"
        :export-collection-name="collectionTitle"
        :export-updated-at="exportUpdatedAt"
        :export-attribution="exportAttribution"
      />
    </div>
    <!-- full_width with no spec yet (e.g. timeseries not yet generated by backend) -->
    <div v-else-if="step.layout === 'full_width'" class="py-6 text-sm text-gray-400 italic">
      Visualisierung für diesen Schritt noch nicht verfügbar.
    </div>

    <!-- Layout: split — two equal charts side by side -->
    <div
      v-else-if="step.layout === 'split'"
      class="grid auto-rows-[minmax(300px,auto)] grid-cols-1 gap-4 sm:grid-cols-2"
    >
      <template v-for="el in splitVisualElements" :key="el.plot_id">
        <ClientOnly v-if="mapLibreSpec(el)"
          ><MapLibreRenderElement
            :element="el"
            :ars="ars"
            :export-area-name="areaName"
            :export-ars="ars"
            :export-title="localizedElementTitle(el) || stepTitle"
            :export-subtitle="localizedElementDescription(el) || stepDescription"
            :export-collection-name="collectionTitle"
            :export-updated-at="exportUpdatedAt"
            :export-attribution="exportAttribution"
        /></ClientOnly>
        <CollectionVegaChart
          v-else-if="el.vegalite_spec"
          :ars="ars"
          :element="el"
          :collection-id="collection.id"
          :spec="injectArea(el.vegalite_spec, ars) ?? {}"
          :height="300"
          :export-area-name="areaName"
          :export-ars="ars"
          :export-title="localizedElementTitle(el) || stepTitle"
          :export-subtitle="localizedElementDescription(el) || stepDescription"
          :export-collection-name="collectionTitle"
          :export-updated-at="exportUpdatedAt"
          :export-attribution="exportAttribution"
        />
      </template>
    </div>

    <!-- Layout: image_text — image left (50%) + description right (50%) -->
    <div v-else-if="step.layout === 'image_text'" class="grid grid-cols-1 items-start gap-6 sm:grid-cols-2">
      <DataImage v-if="imageElement" :element="imageElement" :collection-slug="collection.id" :base-url="baseUrl" />
      <div v-else class="flex h-48 items-center justify-center rounded-lg bg-gray-100 text-sm text-gray-400">
        Kein Bild verfügbar
      </div>
      <div class="text-sm leading-relaxed text-gray-600">
        {{ t(step.description) }}
      </div>
    </div>

    <!-- Layout: default — DataProductPanel for all elements -->
    <div v-else>
      <DataProductPanel
        v-if="kpiCollection"
        :collection="kpiCollection"
        :ars="ars"
        :base-url="baseUrl"
        :initial-summary="summary"
        :population="population ?? undefined"
        :municipality-name="areaName"
        :export-updated-at="exportUpdatedAt"
        :export-attribution="exportAttribution"
      />
    </div>
  </div>
</template>

<script setup lang="ts">
import { computed } from "vue";
import type { ResolvedStep } from "~/composables/useCollectionRender";
import { cloneVisualization, asRecord, type EditableSpec } from "~/shared/visualization";
import type { RenderElement, Collection, CollectionSummary } from "~/types/slz-api";
import { useSlzLocale } from "~/composables/useSlzLocale";
import { hasMapVisual, mapLibreSpec } from "~/utils/dataProducts";

const props = defineProps<{
  step: ResolvedStep;
  collection: Collection;
  summary?: CollectionSummary | null | undefined;
  ars: string;
  baseUrl: string;
  population?: number | null | undefined;
  areaName?: string | undefined;
  exportUpdatedAt?: string | undefined;
  exportAttribution?: string | undefined;
}>();

const { t } = useSlzLocale();
const collectionTitle = computed(() => t(props.collection.title) || props.collection.id);
const stepTitle = computed(() => t(props.step.title) || collectionTitle.value);
const stepDescription = computed(() => t(props.step.description));

function localizedElementTitle(element: RenderElement | null | undefined) {
  return t(element?.title);
}

function localizedElementDescription(element: RenderElement | null | undefined) {
  return t(element?.description);
}

// Inject ?area=ARS into every data.url in a Vega-Lite spec (handles layer specs too)
function injectArea(spec: unknown, ars: string): EditableSpec | null {
  if (!spec) return null;
  if (!ars) return cloneVisualization(spec);
  const s = cloneVisualization(spec);
  function patchUrl(input: unknown) {
    const node = asRecord(input);
    const data = asRecord(node?.data);
    if (typeof data?.url === "string") {
      try {
        const u = new URL(data.url);
        u.searchParams.set("area", ars);
        data.url = u.toString();
      } catch {
        /* Optional data or URL parsing may fail; retain the existing fallback. */
      }
    }
    if (Array.isArray(node?.layer)) node.layer.forEach(patchUrl);
  }
  patchUrl(s);
  return s;
}

// Build a synthetic collection scoped to this step's elements for DataProductPanel
const kpiCollection = computed((): Collection => ({
  ...props.collection,
  render_elements: props.step.elements,
}));

const primaryElement = computed(() => props.step.elements[0] ?? null);

// primary element's Vega spec with area injected (for full_width / split)
const primarySpec = computed(() =>
  !primaryMapLibreSpec.value && primaryElement.value?.vegalite_spec
    ? injectArea(primaryElement.value.vegalite_spec as object, props.ars)
    : null,
);
const primaryMapLibreSpec = computed(() => mapLibreSpec(primaryElement.value));

const mapElement = computed(() => props.step.elements.find((e) => e.type === "map" && hasMapVisual(e)) ?? null);

// map spec with area injected
const mapSpec = computed(() =>
  mapElement.value ? injectArea(mapElement.value.vegalite_spec as object, props.ars) : null,
);

const kpiElement = computed(() => props.step.elements.find((e) => e.type === "kpi") ?? null);

const imageElement = computed(() => props.step.elements.find((e) => e.type === "image") ?? null);

const splitVisualElements = computed(() => props.step.elements.filter((e) => mapLibreSpec(e) || e.vegalite_spec));
</script>
